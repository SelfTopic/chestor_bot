"""Расчёт level_progress, см. BATTLE_DESIGN.md ("Формула левел-апа").

level_progress - 0-100%, без округлений, НЕ exp. Чистая функция здесь не
знает ничего о наградах/уведомлениях - это забота LevelUpService."""


def apply_level_progress(current_progress: float, delta: float) -> tuple[float, int]:
    """Возвращает (новый_progress, левел_ап_произошёл: 0 или 1).

    Уровень НИКОГДА не перепрыгивает больше чем на 1 за одно событие,
    независимо от размера delta - даже огромный прирост (см. "принятая
    эмерджентная механика": проигрыш слабому фарм-аккаунту при большом k)
    даёт максимум один левел-ап. При пересечении 100% прогресс сбрасывается
    в 0, а излишек выше 100% просто ОТБРАСЫВАЕТСЯ, а не переносится дальше.

    Не уходит ниже 0% - убыль прогресса НЕ откатывает уровень назад,
    левел-даун этой функцией не поддерживается и не планируется."""

    progress = current_progress + delta

    if progress >= 100:
        return 0.0, 1

    if progress < 0:
        return 0.0, 0

    return progress, 0


def level_progress_bar(progress: float, segments: int = 10) -> str:
    """Строка вида "⬆️◾️◾️◾️◾️◾️▫️▫️▫️▫️▫️" - заполненные (◾️) сегменты идут
    первыми, слева направо, как в обычном progress-баре. Округление -
    ближайший сегмент (50.0% на 10 сегментах = ровно 5 закрашенных)."""

    clamped = max(0.0, min(100.0, progress))
    filled = min(segments, int(round(clamped / 100 * segments)))
    return "⬆️" + "◾️" * filled + "▫️" * (segments - filled)
